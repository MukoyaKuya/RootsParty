(function($) {
    $(document).ready(function() {
        var imageField = $('#id_image');
        var croppingWidget = $('.image-ratio'); // The container or the image itself
        var croppingInput = $('#id_cropping');
        
        // Find the 'image-grading' container which django-image-cropping uses
        var cropContainer = croppingInput.siblings('.jcrop-holder').length ? 
                            croppingInput.siblings('.jcrop-holder') : 
                            croppingInput.parent().find('img').parent(); 

        // If django-image-cropping hasn't initialized (new object), the structure is different.
        // Usually, there is an img tag with class 'crop-box' or similar if an image exists.
        // If not, we might need to create the img tag.

        imageField.on('change', function(e) {
            if (this.files && this.files[0]) {
                var reader = new FileReader();

                reader.onload = function(e) {
                    // Destroy existing Jcrop if any
                    // We need to find the image element being cropped.
                    // django-image-cropping usually adds a class 'image-ratio' to the widget?
                    // Actually, let's look for the image element generated by the widget.
                    // It usually has an id related to the field, but might depend on the widget implementation.
                    
                    // The raw widget outputs the image if it exists. 
                    // For new uploads, we need to inject the image into the DOM where Jcrop expects it 
                    // or manually initialize Jcrop.

                    // Let's rely on the fact that django-image-cropping puts the image in a specific place.
                    // Or, simpler: we create our own preview and attach Jcrop to it, updating the hidden input.
                    
                    var newImageSrc = e.target.result;
                    
                    // 1. Check if there is already an image crop box
                    var existingImg = $('.crop-thumb'); // django-image-cropping often uses this class or similar
                    
                    // Actually, inspecting the DOM would have been better, but let's try a robust approach.
                    // The hidden input has data attributes: data-ratio, etc.
                    
                    var ratio = croppingInput.data('ratio');
                    var boxWidth = croppingInput.data('box-width') || 600;
                    var boxHeight = croppingInput.data('box-height') || 400;

                    // Container for the preview
                    var previewContainer = croppingInput.parent().find('.crop-preview-container');
                    if (previewContainer.length === 0) {
                        previewContainer = $('<div class="crop-preview-container" style="margin-top: 10px;"></div>');
                        croppingInput.after(previewContainer);
                    }
                    
                    // clear container
                    previewContainer.empty();
                    
                    // Create new image
                    var img = $('<img />', {
                        src: newImageSrc,
                        id: 'jcrop-target-new',
                        style: 'max-width: 100%;' // Ensure it fits
                    });
                    
                    previewContainer.append(img);
                    
                    // Initialize Jcrop
                    img.Jcrop({
                        aspectRatio: ratio,
                        boxWidth: boxWidth,
                        boxHeight: boxHeight,
                        onSelect: updateCoords,
                        onChange: updateCoords,
                        trueSize: null // We don't know the true size yet, Jcrop will figure it out from the loaded image? 
                                       // Actually FileReader gives base64. 
                    }, function() {
                        // Store the API
                        var jcrop_api = this;
                        
                        // Set a default selection?
                        // jcrop_api.setSelect([0, 0, 100, 100]);
                    });

                    function updateCoords(c) {
                        // django-image-cropping expects string: "x,y,w,h"
                        // But wait, it might expect the values relative to the original image size?
                        // The default widget acts on the ORIGINAL image.
                        // If we are cropping a resized preview, we might have scaling issues unless we handle trueSize.
                        // However, for a quick new upload, usually the "preview" IS the full image source (base64).
                        // So trueSize corresponds to the natural width of the base64 image.
                        
                        croppingInput.val(Math.round(c.x) + ',' + Math.round(c.y) + ',' + Math.round(c.x2) + ',' + Math.round(c.y2));
                    }
                }

                reader.readAsDataURL(this.files[0]);
            }
        });
    });
})(django.jQuery);
